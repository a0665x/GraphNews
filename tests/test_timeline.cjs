const assert=require('node:assert/strict');
const timeline=require('../dist/timeline.js');
const defs=[{id:'chips',name:'晶片',color:'#fff'},{id:'financial',name:'財報',color:'#aaa'},{id:'other',name:'未分類',color:'#bbb'}];
const a=(id,date,primary,channels=[primary])=>({id,title:id,published_at:date,primary_channel:primary,channels:channels.map(id=>({id})),source:{provider:'google'}});
const view={articles:[a('later','2026-01-05T12:00:00Z','financial'),a('first','2026-01-01T00:00:00Z','chips',['chips','financial']),a('same','2026-01-01T00:00:00Z','chips'),a('unknown',null,'other')],relations:[{id:'edge',source:'first',target:'later',scope:'cross'}]};
let result=timeline.layout(view,defs,{start:'2026-01-01',end:'2026-01-07',width:1200});
const byId=new Map(result.nodes.map(n=>[n.id,n]));
assert(byId.get('first').x<byId.get('later').x);
assert.equal(byId.get('first').x,byId.get('same').x,'Identical timestamps have identical x positions');
assert.notEqual(byId.get('first').y,byId.get('same').y,'Dense date bins stack vertically');
assert.equal(result.edges[0].a.lane,'chips');assert.equal(result.edges[0].b.lane,'financial');
assert.equal(byId.get('unknown').x,185,'Unknown dates use an explicit gutter, not a guessed time');
let filtered=timeline.filter(view,'financial','2026-01-03');
assert.deepEqual(filtered.articles.map(a=>a.id),['first']);assert.equal(filtered.relations.length,0);
result=timeline.layout(filtered,defs,{start:'2026-01-01',end:'2026-01-07',channel:'financial'});
assert.equal(result.lanes.length,1,'Single channel filtering hides unrelated empty lanes');
assert.equal(result.nodes[0].lane,'financial','Secondary classification can be explored in its own lane');
const zones=timeline.range([a('z','2026-01-02T00:30:00+08:00','chips')]);
assert.equal(zones.startDate,'2026-01-01','Timeline is consistently UTC');
console.log('PASS: UTC ordering, channels, multi-label filtering, collision layout and unchanged cross-lane relations');
